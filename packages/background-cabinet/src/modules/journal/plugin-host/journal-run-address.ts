/**
 * Адрес и отпечаток прогона для плагина, смонтированного к дому журнала.
 *
 * Закрывает ДВА пробела, которые объявление интерфейса называло само (`MODULE_INTERFACE.md`,
 * «Чего здесь ещё нет», пп. 1 и 3). Блок c1 спринта `chart-list-plugin`.
 *
 * ── ПРОБЕЛ 1: чем адресуется прогон ───────────────────────────────────────────────────────
 *
 * `RunAddress` требует пятым полем `collectionId`, а журнал коллекцией не является. Поле читается
 * ПО РОЛИ, а не по имени: в адресе оно значит «набор, по которому шёл прогон». Для дома коллекций
 * набор — коллекция; для дома журнала — журнал. Отсюда `collectionId = 'journal'`.
 *
 * Почему НЕ `journal:<userId>`, хотя так адрес был бы уникальнее. Адрес уезжает в базу результатов
 * офиса, а офис по Т4 — административный сервер команды; пользовательский домен живёт в кабинете.
 * Сегодня `collectionId` идентификатора пользователя в офис не вносит (`__buffer__` — константа),
 * и вводить его ради адреса значило бы протащить пользовательский слой на административный мимо Т4.
 *
 * Почему НЕ id коллекции-источника. Журнал источником коллекцию не имеет: `LiveJournalItemRow` не
 * несёт ни `collectionId`, ни `deviceId`, лента собирается из собственных таблиц кабинета. А
 * `__buffer__` — приёмный буфер, уборку которого владелец назвал предметом отдельного плагина:
 * адресовать долгоживущую выборку тем, что подметается, нельзя.
 *
 * Названная цена НЕ тронута: два прогона с разными настройками расходятся только `runId`, как и
 * принято сознательно. Вердикт M3′ не переоткрывается.
 *
 * ── ПРОБЕЛ 2: что считать `inputHash` ─────────────────────────────────────────────────────
 *
 * Хеш от СОСТАВА `entryIds`, не от их содержимого.
 *
 * Журнал — хроника факта: запись после создания не меняется, значит состав определяет содержимое.
 * Хеш содержимого потребовал бы ЗВУКА, которого у журнала нет вовсе (`audio-not-here`), — отпечаток,
 * который модуль не может вычислить из того, чем владеет, есть обещание, а не отпечаток.
 *
 * Отличие от `inputHashOf` коллекций намеренное и объяснимое: там в строку входит `contentHash`,
 * потому что у media блоб под рукой. Здесь его нет — и подставлять пустоту вместо него значило бы
 * делать вид, что содержимое учтено.
 *
 * СОСТАВ, А НЕ ПОРЯДОК: адреса сортируются, как у соседа. То же задание, поданное в другом порядке,
 * остаётся тем же заданием, и отпечаток обязан это признавать.
 *
 * ── ЧЕМ ДВА ОТВЕТА ДЕРЖАТ ДРУГ ДРУГА ──────────────────────────────────────────────────────
 *
 * Блок C коворка возражал: адрес-затычка сделает два разных задания неразличимыми. Возражение
 * снимается ОТПЕЧАТКОМ, а не адресом: разный состав `entryIds` даёт разный `inputHash`. Адрес
 * говорит «по какому набору», отпечаток — «по какой его части». Требовать различимости от адреса
 * значит требовать от поля работы, для которой оно не заведено.
 */
import { createHash } from 'node:crypto';

import { JOURNAL_HOME } from './home';

/**
 * Имя набора для прогонов дома журнала.
 *
 * Константа, а не вычисление: «журнал этого пользователя» как НАБОР один, чей он — сведение
 * кабинета, и в адрес оно не едет.
 */
export const JOURNAL_RUN_COLLECTION_ID = 'journal';

const sha256Hex = (s: string): string => createHash('sha256').update(s, 'utf8').digest('hex');

/**
 * Отпечаток входа для задания из ленты.
 *
 * Пустое задание отпечатка не получает: до плагина оно не доходит вовсе — `verifyJournalTask`
 * отвергает его причиной `empty-task`. Хеш пустой строки здесь был бы отпечатком того, чего не
 * было.
 */
export function journalInputHash(entryIds: readonly string[]): string {
  if (entryIds.length === 0) {
    throw new Error('journalInputHash: пустое задание отпечатка не имеет — оно отвергается до плагина');
  }
  const unique = [...new Set(entryIds)].sort();
  return sha256Hex(unique.join('\n'));
}

export interface JournalRunAddress {
  readonly pluginId: string;
  readonly version: string;
  readonly collectionId: string;
  readonly runId: string;
  readonly mountTarget: string;
}

/**
 * Адрес прогона журнала. `runId` приходит извне — его рождает тот, кто заказывает прогон, и
 * выдумывать его здесь значило бы прятать источник уникальности внутрь адресатора.
 */
export function journalRunAddress(pluginId: string, version: string, runId: string): JournalRunAddress {
  return {
    pluginId,
    version,
    collectionId: JOURNAL_RUN_COLLECTION_ID,
    runId,
    mountTarget: JOURNAL_HOME,
  };
}
