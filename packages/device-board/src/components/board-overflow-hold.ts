/**
 * Факт «буфер полон» на доске устройства (4/4 коворка `buffer-full-stop`, #2310, вердикт M5 (в)).
 *
 * Доска — ВТОРОЙ вход того же окна оператора, что и панель микрофона; слов о причинах у неё
 * своих нет: все строки приходят готовыми из единственной таблицы код→текст клиента
 * (`apps/client/src/lib/overflow-window/reasonTexts.ts`). Пакет рисует факт, не судит его.
 */
export interface BoardOverflowHoldView {
  /** Ключ факта: `overflowId` сервера либо локальный ключ эпизода до повышения. */
  readonly overflowKey: string;
  /** Причина словами — из таблицы клиента (таблицы в пакете нет). */
  readonly reasonText: string;
  /** Фаза удержания словами («удержание · подтверждено сервером» / «… ещё не подтверждено»). */
  readonly phaseText: string;
  /** Остаток по оси причины («свободно 0 B из 1.0 MB»). */
  readonly remainingText: string;
  /** Согласованная с кабинетом лексика M4: «жив, не пишет». */
  readonly aliveText: string;
  /** Подсказка бейджа (время факта и т.п.). */
  readonly title: string;
  /** Клик по бейджу — то же окно того же `overflowId`; без обработчика бейдж — только показ. */
  readonly onOpenWindow?: () => void;
}
