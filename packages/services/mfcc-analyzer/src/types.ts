/**
 * Контракт MFCC-ядра. Термины назначены структурщиком (Ожегов) в блоке `mfcc-core-wrapper`
 * спринта `mfcc-compare-sprint` — не по вкусу автора, а его актом.
 *
 * ПОЧЕМУ ИМЕНА ИМЕННО ТАКИЕ. В дереве уже живёт FFT-ядро (`@membrana/fft-analyzer-service`),
 * и два ядра обязаны быть неразличимо разными на уровне слов, иначе через полгода никто не
 * скажет, что чем считается. FFT отдаёт **частотные бины** — линейная шкала, есть фазы.
 * MFCC отдаёт **кепстральные коэффициенты** — свёрнутый контур, без фаз и без линейной шкалы.
 * Поэтому `MfccVector`, а не `Spectrum` и не `FftResult`.
 */

/**
 * Вход ядра — **готовый кадр**, а не поток и не сырой `Float32Array`.
 *
 * Граница пакета (решение структурщика): резать сигнал на окна и считать хоп —
 * дело `audio-engine-service`. Ядро кадрированием не занимается: смешение роли кадрирования
 * и спектральной свёртки ломает границу foundation/analyzer, и тогда у одного модуля
 * оказывается два несвязанных предмета.
 */
export interface AudioWindow {
  /** Сэмплы кадра. Длина обязана совпадать с `MfccConfig.bufferSize`. */
  readonly samples: Float32Array;
  readonly sampleRate: number;
  /** Индекс первого сэмпла кадра в исходном потоке — адресует кадр во времени. */
  readonly startIndex: number;
  /** Узел графа, породивший кадр; `null`, если источник не назван. */
  readonly nodeId: string | null;
}

/**
 * Настройки свёртки. Все три параметра проверены предикатом допуска (`melBands`,
 * `numberOfMFCCCoefficients`, `bufferSize` задаются вызовом, а не пересборкой) — но проверка
 * шла на пакете, установленном ВНЕ этого дерева. **В репозитории `meyda` не установлена**, и
 * предикат здесь не воспроизводится: поймано исполнителем блока `mfcc-compare-run`. Прежняя
 * формулировка «проверено на живом пакете» читалась как «проверяемо здесь» — это была неточность
 * автора, а не проверки.
 *
 * Значения по умолчанию НЕ назначены здесь намеренно: речевые умолчания (26/13/25 мс) для
 * дрона слишком компактны, а свои числа берутся подбором на своих записях — сетка
 * 16–40 фильтров / 13–30 коэффициентов / кадр 25–100 мс. Ядро числа не выбирает, оно их
 * принимает.
 */
export interface MfccConfig {
  /** Число мел-фильтров. */
  readonly melBands: number;
  /** Число кепстральных коэффициентов на выходе. */
  readonly numberOfCoefficients: number;
  /** Размер кадра в сэмплах — он же длина `AudioWindow.samples`. */
  readonly bufferSize: number;
}

/**
 * Выход ядра — вектор кепстральных коэффициентов одного кадра.
 *
 * `configHash` носится вместе с вектором намеренно: два вектора, посчитанные разными
 * настройками, **несравнимы**, и без метки это выясняется только по странным цифрам в отчёте.
 */
export interface MfccVector {
  readonly coefficients: Float32Array;
  /** Адрес кадра во времени — тот же `startIndex`, что у входа. */
  readonly windowStartIndex: number;
  /** Отпечаток настроек свёртки; сравнивать векторы с разными отпечатками запрещено. */
  readonly configHash: string;
}

/**
 * Извлекатель коэффициентов. Существует как **тип шва**, а не как удобство тестов:
 * `meyda` прячется целиком за периметром `core/`, и её тип наружу не проходит. Замена
 * библиотеки на другую или на собственный DCT не должна требовать правок за пределами ядра.
 */
export type MfccExtractor = (samples: Float32Array, config: MfccConfig) => readonly number[];

/** Отказ ядра — легальное «нет» с причиной, а не бросок и не пустой массив. */
export interface MfccRefusal {
  readonly ok: false;
  readonly reason: string;
}

export type MfccResult = { readonly ok: true; readonly vector: MfccVector } | MfccRefusal;
