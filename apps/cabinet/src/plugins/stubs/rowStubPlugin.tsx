/**
 * Жилец-заглушка — ВСПОМОГАТЕЛЬНЫЙ стаб блока B, а не продукт.
 *
 * Нужен затем, чтобы механизм принимался на живой странице до появления настоящего жильца:
 * настоящий чарт-лист приедет вторым заданием и должен встать в это же гнездо без правок
 * механизма. Заглушка рисует одну строку и ничего не считает.
 *
 * Регламент коворка: стаб в интеграционную ветку не мёржится; стаб, доживший до прода, есть
 * дефект интеграции. Вынесен в отдельный каталог `stubs/`, чтобы его было видно и легко снять.
 */
import type { CabinetPagePlugin } from '../pagePlugins';

export const ROW_STUB_PLUGIN_ID = 'membrana.showcase.row-stub';

export function createRowStubPlugin(): CabinetPagePlugin {
  return {
    id: ROW_STUB_PLUGIN_ID,
    name: 'Строка-заглушка',
    description: 'Стаб блока B: занимает гнездо, пока не приедет настоящий жилец.',
    form: 'row',
    renderSettings: () => (
      <p className="text-xs text-base-content/60">
        Настроек нет — заглушка. Настоящие настройки жильца появятся здесь же, в сайдбаре.
      </p>
    ),
    renderWidget: () => (
      <p className="text-sm" data-testid="row-stub-widget">
        Здесь будет виджет жильца. Пока это одна строка стаба.
      </p>
    ),
  };
}
