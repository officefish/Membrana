/**
 * Перевязка прибора на другой аккаунт — ДВА действия, и второе до 26.09 нигде не называлось
 * (#2461).
 *
 * В приборе две независимые привязки:
 *  - Студия (этот интерфейс и доска) работает от имени прибора, который назвал кабинет в ответ
 *    на ключ доступа, вставленный здесь. Записи со сценария отправляет она сама;
 *  - служба узла — отдельный БЕЗГОЛОВЫЙ тракт (ADR-0027) — держит свой ключ узла и свой
 *    `FIELD_NODE_DEVICE_ID` в `C:\membrana-node\.env`, берёт задания «снять пробу» из очереди
 *    своего прибора и шлёт пульс. О вставленном здесь ключе доступа она не узнаёт.
 *
 * 25.09 владелец вставил новый ключ в Студию и считал, что прибор перевязан целиком. Служба
 * продолжала работать от имени прибора прежнего аккаунта, и расхождение ничем не объявлялось.
 *
 * ГРАНИЦА УТВЕРЖДЕНИЯ. Первая редакция этого текста говорила «записи не уходят никуда» — лишний
 * вывод, снятый поправкой ведущей 26.09. Отсутствие проб 25.09 расхождением НЕ объясняется:
 * доска пишет своим трактом Студии (`server-storage-backend` → `POST
 * /v1/devices/<deviceId>/collections/<id>/samples`) и после перевязки пишет от имени НОВОГО
 * прибора. Расхождение стоит чинить само по себе, но приписывать ему чужие последствия нельзя:
 * причина того вечера пока не названа, и текст не вправе делать вид, что названа.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ, А НЕ ТЕКСТОМ В РАЗМЕТКЕ. Второе действие — предмет проверки, а не
 * украшение подсказки: зуб рядом стоит на том, что шагов ровно два, что второй называет службу,
 * файл её привязки, чем её перевязать и чем сверить. Текст внутри JSX никакой зуб не удержит —
 * среда тестов клиента `environment: 'node'`, разметку она не рендерит.
 *
 * Границы честно: Студия НЕ МОЖЕТ проверить вторую привязку сама. Её окно — песочница Electron,
 * каждый путь к диску выведен из `app.getPath('userData')`, а `.env` службы лежит снаружи.
 * Поэтому здесь — называние второго действия, а сверка двух привязок живёт там, где обе половины
 * видны: `yarn node:link-state` (вердикт `binding-split`).
 */

/** Файл, в котором живёт вторая привязка прибора — та, о которой знает только служба узла. */
export const NODE_SERVICE_ENV_PATH = 'C:\\membrana-node\\.env';

/** Глагол сверки: единственное место, где обе привязки видны разом. */
export const NODE_BINDING_CHECK_VERB = 'yarn node:link-state';

export interface NodeRebindStep {
  /** Порядковый номер: человек должен видеть, что действий два, а не одно. */
  readonly n: number;
  readonly title: string;
  readonly detail: string;
}

/**
 * Два действия перевязки, по порядку. Первое человек делает здесь и сейчас, второе — руками на
 * самом приборе; оба названы, потому что молчание о втором и есть дефект #2461.
 *
 * @param deviceId прибор нового аккаунта, если он уже известен (после успешной связи)
 */
export function describeNodeRebindSteps(deviceId?: string | null): readonly NodeRebindStep[] {
  const target = typeof deviceId === 'string' && deviceId.trim() !== '' ? deviceId.trim() : '<прибор нового аккаунта>';
  return [
    {
      n: 1,
      title: 'Ключ доступа — в Студию (это действие)',
      detail:
        'Перевязывает интерфейс: Студия начинает работать от имени прибора нового аккаунта — читать квоту, вести наборы, показывать библиотеку.',
    },
    {
      n: 2,
      title: 'Ключ узла — в службу узла (отдельное действие, на приборе)',
      detail:
        `Служба узла — отдельный безголовый тракт: она сама берёт задания «снять пробу» из очереди своего прибора и шлёт пульс. Свой прибор и свой ключ она держит в ${NODE_SERVICE_ENV_PATH} ` +
        'и о вставленном здесь ключе доступа не узнаёт. Пока там прежний прибор, её задания и пульс уходят на прибор прежнего аккаунта. ' +
        'Записи со сценария доски это не затрагивает — их Студия отправляет сама и уже от имени нового прибора. ' +
        `Выпустить ключ узла прибору ${target} (POST /v1/devices/${target}/node-key?rotate=true) и переустановить службу: ` +
        `powershell -File firebat-service-install.ps1 -DeviceId ${target} -NodeKey <сырой ключ>. ` +
        `Сверить, что привязки сошлись: ${NODE_BINDING_CHECK_VERB}.`,
    },
  ];
}
