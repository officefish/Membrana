/**
 * Canonical evening ritual outputs that must land on origin/main (ritual-deliver-to-main).
 *
 * Близнец `ritual-morning-artifacts.mjs`. Заведён спринтом `ritual-tails-sprint`, блок
 * `ritual-evening-manifest-and-delivery`, находка Ф2 разбора #1533: у вечера НЕТ кадра
 * доставки, при том что у утра он есть с рабочим движком — и потому вечер структурно
 * заканчивается на ветке. Цена названа фактом: архив дня 29.07 пролежал на локальной ветке
 * соседнего дерева двое суток и доехал до main руками 31.07, после того как ревью нашло его
 * повторно.
 *
 * ПРОЕКЦИЯ, НЕ ДУБЛИРОВАНИЕ (решение архитектора): каждый шаг цепочки объявляет в
 * `produces[]`, что рождает; этот список — проекция тех объявлений на вопрос «что обязано
 * доехать до ствола».
 *
 * СПИСОК СУЖЕН ДО ПРОВЕРЯЕМОГО, и это не произвол. Движок сверяет СОДЕРЖИМОЕ ФАЙЛА
 * (`readDated` → сравнение с origin/main) и требует сегодняшней даты в документе. Значит
 * в список не входят:
 *
 * - `docs/archive/daily-day/<date>/` — КАТАЛОГ, и его опись `manifest.json` тоже вне списка.
 *   Опись — JSON, а гейт свежести читает `<!-- Сгенерировано: … -->`, которого в JSON быть не
 *   может. Датированность у описи ЕСТЬ (`dayKey`, `archivedAt`), но принимать её значило бы
 *   завести ВТОРУЮ форму проверки свежести в движке доставки — резчик назвал это смешением
 *   дела: проверка свежести обязана жить в одном месте. Вопрос о втором виде провенанса —
 *   отдельная работа, не эта. До неё опись проверяется своим шагом архива, а не доставкой.
 * - `docs/archive/daily-code-review/` — каталог, имена внутри несут метку времени прогона
 *   (`DAILY_CODE_REVIEW-<ISO>.md`), предсказать имя по дате нельзя. Содержимое при этом
 *   производно от `docs/DAILY_CODE_REVIEW.md`, который в списке есть.
 * - `docs/tasks/truth-registry.json` — не датированный документ: гейт свежести назвал бы
 *   его `stale` в любой день. Остывание графа правды проверяется своим шагом, не доставкой.
 * - `docs/seanses/team-memory-report-<date>.md` — рождается НЕКРИТИЧНЫМ шагом, законно
 *   отсутствует при сбое отчёта. Включить значило бы дать `missing-local` STOP на живом
 *   вечере — ложный красный ценой в остановку ритуала.
 *
 * Исключения названы здесь, а не молчат: «производные снимки отстают молча» — тот самый
 * класс, ради которого этот спринт и начат.
 */

/**
 * ПЕРВЫЙ НАСТОЯЩИЙ ПРОГОН КАДРА 01.08 ПОКАЗАЛ, ЧТО ОН НЕПРОХОДИМ В ПРИНЦИПЕ — и не потому,
 * что артефактов нет, а по дефекту этого списка. Из шести позиций доставкой лечились ДВЕ;
 * остальные четыре падали на том, чего у них не могло быть: конспект мостика требовался
 * безусловно, хотя мостик открывают не каждый день, а у трёх файлов не было строки провенанса.
 *
 * Довод против такого списка был записан здесь же, но применён к ОДНОЙ позиции — отчёту
 * памяти команды. К остальным тот же довод не применили, и гейт получился не защитой, а
 * стеной: он останавливал вечер независимо от того, доехали артефакты или нет.
 *
 * УСЛОВИЕ ВЕШАЕТСЯ НА НЕЗАВИСИМОГО СВИДЕТЕЛЯ, а не на сам файл. Первая редакция лечения
 * спрашивала «есть ли файл» — то есть проверка отменялась тем же, чего касается. Резчик
 * назвал это затвором: «условность — способ гасить проверки, когда неудобно», и был прав.
 * Свидетель у мостика свой: `docs/bridge/state.json` несёт `day` и `phase`. Мостик сам
 * говорит, открывали ли его. Отсюда различение, которого не было:
 *
 *   мостик не открывали → конспекта нет → ЗАКОННО
 *   мостик открывали    → конспекта нет → НАХОДКА
 *
 * Провенанс же чинится У ИСТОЧНИКА: генератор обязан подписывать то, что рождает. Правка
 * списка вместо генератора была бы сокрытием — документ остался бы непроверяемым и просто
 * перестал бы об этом говорить.
 */

/**
 * СПИСОК — КАТАЛОГ ФАКТОВ, БЕЗ УСЛОВИЙ. Разбор структурщика и архитектора, блоки
 * `deliver-list-flags` и `deliver-engine-conditional`: признак условности в записи артефакта
 * — протечка поведения в перечень. Структурщик: «реестр очистить до безусловного списка
 * фактов». Архитектор: «если это каталог фактов, `when` лишний; держать список чистым, движок
 * сам решает, включать ли позицию».
 *
 * Первая редакция лечения несла в записи поле `when: 'bridge-open'` — и оба держателя его
 * отвергли. Условность вынесена туда, где ей место: в конфигурацию вечернего ритуала
 * (`DELIVER_RITUALS.evening.artifacts`), которая и есть носитель знания об особенностях
 * СВОЕЙ процедуры. Общий движок при этом остаётся общим — он не знает про мостик, а список
 * не знает про условия.
 */

/** @typedef {{ rel: string, label: string, dated: boolean }} EveningDeliverArtifact */

/** @type {EveningDeliverArtifact[]} */
export const EVENING_DELIVER_ARTIFACTS = Object.freeze([
  { rel: 'docs/DAILY_CODE_REVIEW.md', label: 'DAILY_CODE_REVIEW', dated: false },
  { rel: 'docs/seanses/team-evening-feedback-<date>.md', label: 'протокол командного фидбека', dated: true },
  { rel: 'docs/seanses/workspace-level-<date>.md', label: 'отчёт выравнивания', dated: true },
  { rel: 'docs/memos/<date>.md', label: 'DAY_MEMO', dated: true },
  { rel: 'docs/bridge/<date>/CONSPECTUS.md', label: 'конспект мостика', dated: true },
]);

/**
 * Позиции, существующие не каждый день, и их свидетель.
 *
 * Отдельной картой, а не полем записи: список остаётся каталогом фактов, а знание «этот
 * артефакт рождается лишь по такому-то условию» принадлежит ПРОЦЕДУРЕ вечера, не перечню.
 *
 * Свидетель у мостика свой — `docs/bridge/state.json`. Спрашивать «есть ли файл конспекта»
 * значило бы отменять проверку тем же, чего она касается; резчик назвал такую условность
 * затвором.
 */
export const EVENING_CONDITIONAL = Object.freeze({
  'docs/bridge/<date>/CONSPECTUS.md': 'bridge-open',
});

/**
 * @param {string} date `YYYY-MM-DD`
 * @param {readonly EveningDeliverArtifact[]} [artifacts]
 * @returns {string[]}
 */
export function eveningDeliverPaths(date, artifacts = EVENING_DELIVER_ARTIFACTS) {
  return artifacts.map((a) => (a.dated ? a.rel.replaceAll('<date>', date) : a.rel));
}

/**
 * Разрешает `<date>` в описаниях артефактов — движку нужен список с готовыми путями,
 * но с сохранёнными метками, иначе отчёт печатает путь вместо человеческого имени.
 *
 * @param {string} date `YYYY-MM-DD`
 * @param {readonly EveningDeliverArtifact[]} [artifacts]
 * @returns {{ rel: string, label: string }[]}
 */
export function eveningDeliverArtifacts(date, artifacts = EVENING_DELIVER_ARTIFACTS) {
  // Поля выбираются ЯВНО, а не спредом. Требование структурщика: спред копирует всё, что было
  // в исходной записи, и служебное поле, заведённое завтра, молча просочилось бы в ствол.
  // Явный выбор закрывает ровно то, что нужно, и ломается заметно, когда список вырастет.
  return artifacts.map((a) => ({
    rel: a.dated ? a.rel.replaceAll('<date>', date) : a.rel,
    label: a.label,
    dated: a.dated,
  }));
}

/**
 * Условен ли артефакт вечера, и по какому свидетелю. Ключ — ШАБЛОННЫЙ путь из каталога,
 * поэтому карта не зависит от даты прогона.
 *
 * @param {string} relTemplate
 * @returns {string|null}
 */
export function eveningConditionOf(relTemplate) {
  return EVENING_CONDITIONAL[relTemplate] ?? null;
}
