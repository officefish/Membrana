/**
 * Свежесть владельческого источника магистрали — чистый предикат, без ФС и часов.
 *
 * ЧТО ИЗМЕРЯЕТСЯ. У магистрали дня два владельческих источника: `sources[0]` в
 * `docs/tasks/main-day-assertions.json` (чеканится рукой) и `magistral` в
 * `docs/tasks/morning-gates-state.json` (кладётся утренним гейтом вместе с `frozenDigest`
 * снимка топ-3 и днём выбора). Они расходятся, и норма У1 от 31.07 этот спор уже разрешила:
 * если день гейта сегодняшний, его выбор ПОЗДНЕЕ, магистраль берётся с гейта, а расхождение
 * не замалчивается.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО. Правила разрешения спора. Норма У1 живёт в задании
 * генератора, и этот предикат её ИЗМЕРЯЕТ, а не переиспользует и не переписывает: кросс-импорт
 * `_main-day-issue.mjs` завёл бы вторую редакцию нормы (запрет структурщика 02.08).
 *
 * ПОЧЕМУ ЭТО ВООБЩЕ ПРЕДИКАТ. До 02.08 расхождение предъявлялось ИНСТРУКЦИЕЙ В ПРОМПТЕ —
 * генератору велено назвать его строкой в таблице. Инструкцию исполняет языковая модель, и
 * ничто не заметило бы, если однажды строка не будет написана. Тот же класс, что у прибора
 * сирот и у дозора зависимостей в этот же день: механизм проверяет, что шаг отработал, и не
 * проверяет, что шаг покрыл свой предмет.
 */

/**
 * Исходы сверки. Список закрыт четырьмя: третьей стороны у спора нет, а «испорчен вход» —
 * не исход сверки, а отказ от неё (см. `E_SOURCES_MALFORMED`).
 */
export const FRESHNESS = Object.freeze({
  /** Гейт сегодняшний и его выбор совпал с самым свежим источником — расхождения нет. */
  ALIGNED: 'aligned',
  /**
   * Гейт сегодняшний, а самый свежий источник старше либо называет иное.
   *
   * ИМЯ ГОВОРИТ О СВЕЖЕСТИ, НЕ О ПРИОРИТЕТЕ (закреплено структурщиком 02.08): «гейт свежее»
   * — наблюдение о датах. Что из этого следует, решает норма У1, а не этот предикат.
   */
  GATE_NEWER: 'gate_newer',
  /** Гейта нет либо его день не сегодняшний — сверять не с чем, расхождением это не является. */
  NO_GATE: 'no_gate',
  /** Источников нет вовсе — «магистраль владельцем не задана», отдельный факт от `aligned`. */
  NO_SOURCES: 'no_sources',
});

/**
 * Порча входа: не исход сверки, а отказ её выносить. Два кода, и разделены они по ВЛАДЕЛЬЦУ
 * порчи, а не по месту обнаружения (правило структурщика 02.08: красное за нарушением, а
 * наблюдение остаётся зелёным).
 *
 * `E_SOURCES_MALFORMED` — испорчен вещдок дня: список не список, дата не дата, дата из будущего.
 * Это структурное нарушение `sources`, и оно РОНЯЕТ гейт.
 *
 * `E_GATE_MALFORMED` — испорчено состояние утреннего гейта. Гейт пишется инструментом, вещдок
 * дня к его порче непричастен, и ронять день чужой поломкой значило бы наказать не того. Сверка
 * не выносится, причина называется, код возврата остаётся нулевым.
 */
export const E_SOURCES_MALFORMED = 'E_SOURCES_MALFORMED';
export const E_GATE_MALFORMED = 'E_GATE_MALFORMED';

const isFilled = (v) => typeof v === 'string' && v.trim() !== '';

/**
 * День в виде `YYYY-MM-DD`, и только так.
 *
 * СРАВНЕНИЕ ДАТ ЗДЕСЬ СТРОКОВОЕ, и это законно ровно при этом формате: лексикографический
 * порядок совпадает с календарным при ведущих нулях. Разбор Дынина 02.08 назвал цену
 * отсутствия проверки: `2026-8-2`, `2026/08/02`, `20260802` прошли бы как «непустая строка» и
 * молча стекли в неверный исход. Расширенные годы (`+10000-…`) не поддержаны сознательно —
 * непонятая дата даёт отказ, а не догадку.
 */
const DAY_RE = /^\d{4}-\d{2}-\d{2}$/u;
const isDay = (v) => typeof v === 'string' && DAY_RE.test(v);

/**
 * Сверить владельческие источники магистрали.
 *
 * @param {{sources?: unknown}} assertions документ вещдока дня значением
 * @param {{magistral?: string, day?: string}|null} gate состояние утреннего гейта значением
 * @param {string} today день прогона, `YYYY-MM-DD` — ПАРАМЕТР, часов в ядре нет
 * @returns {{verdict: string, reason: string, sourceDate: string|null, gateDay: string|null,
 *   gateMagistral: string|null}}
 */
export function magistralFreshness(assertions, gate, today) {
  const sources = assertions?.sources;
  if (sources !== undefined && !Array.isArray(sources)) {
    return {
      verdict: E_SOURCES_MALFORMED,
      reason: 'sources не список — сверять нечем, вердикта нет',
      sourceDate: null,
      gateDay: null,
      gateMagistral: null,
    };
  }

  const list = Array.isArray(sources) ? sources : [];
  const newest = list[0] ?? null;
  const sourceDate = isFilled(newest?.date) ? newest.date : null;
  const gateDay = isFilled(gate?.day) ? gate.day : null;
  const gateMagistral = isFilled(gate?.magistral) ? gate.magistral : null;
  const base = { sourceDate, gateDay, gateMagistral };

  // Дата, которая есть, но датой не является, — порча. Отсутствие даты порчей НЕ считается:
  // это честное «не сказано», и оно ниже называется своим словом.
  if (sourceDate !== null && !isDay(sourceDate)) {
    return { ...base, verdict: E_SOURCES_MALFORMED, reason: `дата источника «${sourceDate}» не в виде YYYY-MM-DD — сверять нечем` };
  }
  if (isDay(sourceDate) && isDay(today) && sourceDate > today) {
    // Источник из будущего — не «самый свежий», а сбитые часы у чеканщика. Молча считать его
    // свежим значило бы навсегда закрыть расхождение для этого файла.
    return { ...base, verdict: E_SOURCES_MALFORMED, reason: `дата источника ${sourceDate} позже дня прогона ${today} — часы чеканщика сбиты` };
  }
  if (gateDay !== null && !isDay(gateDay)) {
    return { ...base, verdict: E_GATE_MALFORMED, reason: `день гейта «${gateDay}» не в виде YYYY-MM-DD — сверка не выносится, вещдок дня тут ни при чём` };
  }

  if (gateMagistral === null || gateDay !== today) {
    return {
      ...base,
      verdict: FRESHNESS.NO_GATE,
      reason:
        gateMagistral === null
          ? 'утренний гейт магистрали не несёт — сверять не с чем'
          : `день гейта ${gateDay} ≠ день прогона ${today} — выбор не сегодняшний, расхождением не считается`,
    };
  }

  if (list.length === 0) {
    return {
      ...base,
      verdict: FRESHNESS.NO_SOURCES,
      reason: `владельческих источников ноль, гейт несёт «${gateMagistral}» — магистраль задана только гейтом`,
    };
  }

  // Совпадением считается СЕГОДНЯШНЯЯ запись: источник вчерашнего дня, случайно назвавший ту же
  // магистраль, расхождение не снимает — вещдок дня всё равно не перечеканен.
  if (sourceDate === today) {
    return {
      ...base,
      verdict: FRESHNESS.ALIGNED,
      reason: `вещдок дня перечеканен сегодня (${sourceDate}), гейт несёт «${gateMagistral}»`,
    };
  }

  return {
    ...base,
    verdict: FRESHNESS.GATE_NEWER,
    reason:
      `вещдок дня несёт источник от ${sourceDate ?? '(без даты)'}, а гейт — выбор от ${gateDay} ` +
      `(«${gateMagistral}»): магистраль берётся с гейта по норме У1, перечеканка НЕ сделана`,
  };
}

/**
 * Строка отчёта. Печатается ВСЕГДА, включая `aligned`: молчание на совпадении неотличимо от
 * «сверки не было», а именно немота и есть дефект, который предикат закрывает.
 */
export function formatFreshness(result) {
  const mark = result?.verdict === FRESHNESS.GATE_NEWER ? '⚠' : '·';
  return `${mark} свежесть посылок: ${result?.verdict} — ${result?.reason}`;
}

/**
 * Роняет ли этот исход гейт.
 *
 * НЕТ НИ НА ОДНОМ (слово структурщика 02.08). `gate_newer` норма У1 разрешает штатно — красный
 * тут ложный и учил бы команду не верить коду 2. `no_sources` семантически то же, что пустой
 * `assertions`, который гейт пропускает. Красное остаётся за ПОСЫЛКАМИ и за порчей входа,
 * то есть за нарушением, а не за наблюдением.
 */
export const blocksDay = (verdict) => verdict === E_SOURCES_MALFORMED;
