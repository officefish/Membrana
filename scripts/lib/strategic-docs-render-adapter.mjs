/**
 * engine-renderer — Phase 2 (executable, pure, test-only stubs)
 * Git is the single source of truth. Affine priority. Non-Affine = home stub.
 */

import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const WORKSPACE_ROOT = join(__dirname, '../../../');
const STRATEGIC_DOCS = join(WORKSPACE_ROOT, 'strategic-docs');

/** @typedef {'affine' | 'notion' | 'coda'} ProviderId */
/** @typedef {'live' | 'stub'} HomeMode */

const DEFAULT_PROVIDER = /** @type {ProviderId} */ ('affine');
const AFFINE_BASE = 'https://affine.mmbrn.tech';

/**
 * @typedef {Object} ReleaseSurface
 * @property {string} releaseId
 * @property {string} version
 * @property {string} title
 * @property {string} markdown
 * @property {Record<string, unknown>} [meta]
 */

/**
 * @typedef {Object} RenderResult
 * @property {ProviderId} provider
 * @property {'rendered' | 'stub'} kind
 * @property {string} url
 * @property {string} [stubMessage]
 * @property {string} localPath
 */

/**
 * @typedef {Object} SyncConflict
 * @property {string} path
 * @property {'git'} winner
 * @property {string} resolution
 */

/**
 * @typedef {Object} SyncResult
 * @property {ProviderId} provider
 * @property {'ok' | 'degraded' | 'failed'} status
 * @property {number} pushed
 * @property {number} pulled
 * @property {SyncConflict[]} conflicts
 * @property {string} [degradedReason]
 */

/**
 * @typedef {Object} AdapterContext
 * @property {ProviderId} [selectedProvider]
 * @property {string} [affineBaseUrl]
 * @property {string} [workspaceRoot]
 * @property {object} [stubs]
 * @property {(msg: string, meta?: object) => void} [log]
 */

const defaultStubs = {
  affineHealth: async () => 'up',
  notionHealth: async () => 'up',
  codaHealth: async () => 'up',
  providerStore: new Map(),
  readyRelease: {
    releaseId: 'rel-stub-001',
    version: '0.0.0-stub',
    title: 'Stub Release',
    markdown: '# Stub Release\n\nContent generated by generators-validation stub.',
    meta: { pin: 'git:HEAD' }
  }
};

/** @type {Map<string, string>} */
const gitSnapshot = new Map();

/** @param {string} p */
const ensureDir = (p) => {
  const d = dirname(p);
  if (!existsSync(d)) mkdirSync(d, { recursive: true });
};

/** @param {Partial<AdapterContext>} [partialCtx] */
export function createRenderAdapter(partialCtx = {}) {
  const ctx = {
    selectedProvider: /** @type {ProviderId} */ (partialCtx.selectedProvider ?? DEFAULT_PROVIDER),
    affineBaseUrl: partialCtx.affineBaseUrl ?? AFFINE_BASE,
    workspaceRoot: partialCtx.workspaceRoot ?? WORKSPACE_ROOT,
    stubs: { ...defaultStubs, ...partialCtx.stubs },
    log: partialCtx.log ?? ((msg) => console.log(`[engine-renderer] ${msg}`)),
  };

  const providerId = ctx.selectedProvider;

  /** @type {ProviderAdapter} */
  const adapter = {
    id: providerId,
    async render(surface) {
      if (!surface?.releaseId || !surface?.markdown) {
        throw new TypeError('ReleaseSurface must contain releaseId and markdown');
      }

      const health = await getHealth(ctx);
      const isAffine = providerId === 'affine';

      if (isAffine) {
        if (health === 'up') {
          const url = `${ctx.affineBaseUrl}/workspace/release-${surface.releaseId}`;
          const localPath = `strategic-docs/releases/${surface.releaseId}.md`;
          const fullPath = join(STRATEGIC_DOCS, `releases/${surface.releaseId}.md`);
          ensureDir(fullPath);
          writeFileSync(fullPath, surface.markdown, 'utf8');

          return {
            provider: providerId,
            kind: 'rendered',
            url,
            localPath
          };
        } else {
          return createDegradedStub(ctx, surface, 'Affine is down');
        }
      }

      // Non-Affine → home stub with link
      return await stubWithLinkImpl(surface, ctx);
    },

    async sync(surface) {
      const health = await getHealth(ctx);
      if (health !== 'up') {
        return {
          provider: providerId,
          status: health === 'auth-error' ? 'failed' : 'degraded',
          pushed: 0,
          pulled: 0,
          conflicts: [],
          degradedReason: health === 'auth-error' ? 'Authentication error' : 'Provider unreachable'
        };
      }

      const gitSnap = takeGitSnapshot(surface, ctx);
      const provSnap = takeProviderSnapshot(ctx);

      const { pushes, pulls, conflicts } = mergeSnapshots(gitSnap, provSnap, { protectedPins: ['.pin'] });

      // Apply git wins
      for (const [path, content] of pushes) {
        ctx.stubs.providerStore.set(path, content);
      }
      for (const [path, content] of pulls) {
        gitSnapshot.set(path, content);
      }
      for (const c of conflicts) {
        ctx.stubs.providerStore.set(c.path, gitSnap.get(c.path) || '');
      }

      const manifestPath = join(STRATEGIC_DOCS, '.sync-manifest.json');
      ensureDir(manifestPath);
      writeFileSync(manifestPath, JSON.stringify({
        releaseId: surface.releaseId,
        provider: providerId,
        ts: '2025-01-01T00:00:00.000Z', // deterministic
        pushed: pushes.length,
        pulled: pulls.length,
        conflicts: conflicts.length
      }, null, 2), 'utf8');

      return {
        provider: providerId,
        status: 'ok',
        pushed: pushes.length,
        pulled: pulls.length,
        conflicts: conflicts
      };
    },

    async stubWithLink(surface) {
      return stubWithLinkImpl(surface, ctx);
    },

    async health() {
      return getHealth(ctx);
    }
  };

  return {
    async renderRelease(surface) {
      return adapter.render(surface);
    },

    async fullSync(surface) {
      return adapter.sync(surface);
    },

    async renderHomeStub(surface) {
      return adapter.stubWithLink(surface);
    },

    async status() {
      const health = await getHealth(ctx);
      const homeMode = resolveHomeMode(ctx.selectedProvider);
      return {
        provider: ctx.selectedProvider,
        health,
        homeMode
      };
    }
  };
}

/** @param {Partial<AdapterContext>} ctx */
async function getHealth(ctx) {
  const p = ctx.selectedProvider || 'affine';
  const stubs = ctx.stubs || defaultStubs;
  if (p === 'affine') return stubs.affineHealth();
  if (p === 'notion') return stubs.notionHealth();
  return stubs.codaHealth();
}

/**
 * @param {ReleaseSurface} surface
 * @param {Partial<AdapterContext>} ctx
 */
async function stubWithLinkImpl(surface, ctx) {
  const provider = ctx.selectedProvider || 'notion';
  const url = provider === 'notion'
    ? `https://www.notion.so/mmbrn/${surface.releaseId || 'strategic-release'}`
    : `https://coda.io/d/Strategic-Release_${surface.releaseId || 'stub'}`;

  const stubMessage = `Рабочая поверхность: ${provider.toUpperCase()}. Открыть: ${url}. Локальный Affine-контур не активен по выбору оператора.`;

  const localPath = 'strategic-docs/.engine-stub.json';
  const fullPath = join(STRATEGIC_DOCS, '.engine-stub.json');
  ensureDir(fullPath);
  writeFileSync(fullPath, JSON.stringify({
    provider,
    releaseId: surface.releaseId,
    url,
    ts: '2025-01-01T00:00:00.000Z'
  }, null, 2), 'utf8');

  return {
    provider,
    kind: 'stub',
    url,
    stubMessage,
    localPath
  };
}

/** @param {Partial<AdapterContext>} ctx */
function resolveHomeMode(selected = 'affine') {
  return selected === 'affine' ? 'live' : 'stub';
}

/**
 * @param {ReleaseSurface} surface
 * @param {Partial<AdapterContext>} ctx
 */
function takeGitSnapshot(surface, ctx) {
  gitSnapshot.clear();
  gitSnapshot.set('release.md', surface.markdown);
  gitSnapshot.set('.provider-selection.json', JSON.stringify({
    selectedProvider: ctx.selectedProvider || 'affine'
  }, null, 2));
  return new Map(gitSnapshot);
}

/** @param {Partial<AdapterContext>} ctx */
function takeProviderSnapshot(ctx) {
  const store = ctx.stubs?.providerStore || new Map();
  return new Map(store);
}

/**
 * @param {Map<string, string>} gitSnap
 * @param {Map<string, string>} provSnap
 * @param {{protectedPins?: string[]}} opts
 */
export function mergeSnapshots(gitSnap, provSnap, opts = {}) {
  const pushes = [];
  const pulls = [];
  const conflicts = [];
  const protectedPins = opts.protectedPins ?? [];
  const isProtected = (key) => protectedPins.some((suf) => key.endsWith(suf));

  const allKeys = new Set([...gitSnap.keys(), ...provSnap.keys()]);

  for (const key of allKeys) {
    if (isProtected(key)) continue;
    const g = gitSnap.get(key);
    const p = provSnap.get(key);

    if (g !== undefined && p === undefined) {
      pushes.push([key, g]);
    } else if (g === undefined && p !== undefined) {
      pulls.push([key, p]);
    } else if (g !== p) {
      conflicts.push({
        path: key,
        winner: 'git',
        resolution: 'kept-git'
      });
    }
  }

  return { pushes, pulls, conflicts };
}

function createDegradedStub(ctx, surface, reason) {
  return {
    provider: ctx.selectedProvider || 'affine',
    kind: 'stub',
    url: ctx.affineBaseUrl || AFFINE_BASE,
    stubMessage: `Affine degraded: ${reason}`,
    localPath: 'strategic-docs/.engine-stub.json'
  };
}

/** Convenience re-exports */
export const renderRelease = (s, c = {}) => createRenderAdapter(c).renderRelease(s);
export const fullSync = (s, c = {}) => createRenderAdapter(c).fullSync(s);
export const stubWithLink = (s, c = {}) => createRenderAdapter(c).renderHomeStub(s);
export const getEngineStatus = (c = {}) => createRenderAdapter(c).status();
export { resolveHomeMode };
