/**
 * Состояние прогона аудита — страж, без которого сравнение сводок лжёт.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ПРЕДИКАТОМ (поправка резчика 02.08). Сравнение прежней сводки с текущей
 * осмысленно ровно тогда, когда текущая сводка есть. Один моргнувший реестр отдаёт пустой
 * ответ — и наивное сравнение объявляет, что «перестали сообщаться» ВСЕ записи разом. Это тот
 * же род вранья, ради которого правится дозор: утверждение, которого никто не измерял, только
 * масштабом больше.
 *
 * Три состояния, список закрыт. Четвёртого нет, потому что различить «уязвимость исправлена» и
 * «пакет выпал из дерева» аудит не даёт — это уже не состояние прогона, а вопрос к конкретной
 * записи, и он адресуется человеку.
 */

export const AUDIT_STATES = Object.freeze({
  /** Аудит отработал, ответ содержателен — сравнивать можно. */
  OK: 'ok',
  /** Аудит не отработал вовсе (сеть, реестр, пустой stdout) — сравнивать нечего. */
  NOT_RUN: 'not_run',
  /** Аудит вернул пусто там, где прежде было непусто — ответ подозрителен, сравнение запрещено. */
  SUSPECT_EMPTY: 'suspect_empty',
});

/**
 * Определить состояние прогона.
 *
 * @param {{ran: boolean, findings?: ReadonlyArray<object>, previousCount?: number}} run
 *   `ran` — отработал ли аудит (исключение снаружи → `false`); `findings` — что он вернул;
 *   `previousCount` — сколько записей было в прежнем снимке (нет снимка → 0).
 * @returns {{state: string, reason: string}} состояние и человеческая причина
 */
export function auditState(run = {}) {
  const { ran = false, findings = [], previousCount = 0 } = run;
  const count = Array.isArray(findings) ? findings.length : 0;

  if (!ran) {
    return { state: AUDIT_STATES.NOT_RUN, reason: 'аудит не отработал — сравнивать не с чем' };
  }
  if (count === 0 && previousCount > 0) {
    return {
      state: AUDIT_STATES.SUSPECT_EMPTY,
      reason:
        `аудит вернул ноль записей, а в прежнем снимке их ${previousCount} — ` +
        'разом исчезнуть они не могли; сравнение НЕ производится, снимок НЕ перезаписывается',
    };
  }
  return { state: AUDIT_STATES.OK, reason: `аудит отработал, записей ${count}` };
}

/**
 * Можно ли сравнивать сводки при этом состоянии.
 *
 * Отдельная функция, а не сравнение со строкой на местах вызова: «сравнивать нельзя» — решение
 * одно, и жить оно должно в одном месте, иначе два режима дозора разъедутся ровно так, как
 * разъехались до 02.08.
 */
export const comparable = (state) => state === AUDIT_STATES.OK;

/**
 * Можно ли перезаписывать снимок.
 *
 * Совпадает с `comparable` не случайно и всё же объявлено отдельно: перезапись — действие
 * разрушительное (прежний состав теряется безвозвратно), и право на неё обязано читаться
 * в коде своим именем. Подозрительно пустой ответ снимок НЕ затирает — иначе одна осечка
 * реестра стёрла бы историю наблюдения.
 */
export const snapshotWritable = (state) => state === AUDIT_STATES.OK;
