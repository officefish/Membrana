/**
 * Пояснение к `built-invalid`, когда невалидность — это НАЗВАННЫЙ долг, а не поломка.
 *
 * Без него витрина сообщает внешнему читателю «процедура невалидна» и молчит о причине:
 * семь процедур, включая оба ритуала, выглядят сломанными, хотя у них ровно один
 * задокументированный долг, ждущий отдельной задачи. Голая правда без контекста читается
 * как авария — а по ADR-0025 Р3 краснота должна давить на закрытие долга, не пугать.
 *
 * Состояние НЕ подменяется: `built-invalid` остаётся ровно тем, чем был. Добавляется только
 * причина — прятать долг было бы противоположностью Р3.
 */
function buildStateNote(procedure) {
  const problems = procedure.problems ?? [];
  if (problems.length === 0 || !problems.every((p) => isAdr0025Debt(p))) return '';
  const n = problems.length;
  // Склонение руками: страница публичная, «5 фрейма(-ов)» на витрине читается как небрежность.
  const tail = n % 10;
  const teen = n % 100 >= 11 && n % 100 <= 14;
  const word = !teen && tail === 1 ? 'фрейм ждёт' : !teen && tail >= 2 && tail <= 4 ? 'фрейма ждут' : 'фреймов ждут';
  return ` — по названному долгу ADR-0025: ${n} ${word} держателя ([#1787](https://github.com/officefish/Membrana/issues/1787)). Не поломка`;
}
import { discoverContainers } from './tooling-atlas.mjs';

const GENERATED_NOTICE =
  '{/* Generated by `node scripts/mintlify-workflow-docs.mjs --render`. Do not edit. */}';
const GITHUB_ROOT = 'https://github.com/officefish/Membrana/blob/main/';
const EXAMPLE_TASK = 'workflow-examples-marathon';

const clean = (value) => String(value ?? 'не объявлено').replace(/[\r\n]+/gu, ' ').trim();
const mdx = (value) => clean(value).replace(/[{}<>]/gu, (ch) => ({
  '{': '｛',
  '}': '｝',
  '<': '‹',
  '>': '›',
}[ch]));
const sourceUrl = (path) => `${GITHUB_ROOT}${String(path).replace(/\\/gu, '/')}`;
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

export const readDigest = readReadmeDigest;
export const workshopSlug = (home) => home.replace(/^docs\//u, '').replaceAll('/', '-');
export const procedureSlug = (id) => id;

function migrationState(procedure) {
  const values = [procedure.container?.value, procedure.vocabulary?.value, procedure.grammar?.value];
  if (values.every(Boolean)) return 'migrated';
  if (values.some(Boolean)) return 'in-migration';
  return 'legacy';
}

function readProcedureManifest(repoRoot, procedure) {
  if (!procedure.homePath?.startsWith('docs/procedures/')) return null;
  const path = join(repoRoot, procedure.homePath, 'MANIFEST.json');
  return existsSync(path) ? readJson(path) : null;
}

export function loadWorkflowDocsModel(repoRoot) {
  const workshops = discoverContainers(repoRoot)
    .filter((item) => item.kind === 'workshop')
    .map((item) => {
      const digest = readReadmeDigest(join(repoRoot, item.home, 'README.md'));
      return {
        ...item,
        slug: workshopSlug(item.home),
        title: digest.title ?? item.name,
        summary: digest.summary ?? item.summary,
      };
    })
    .sort((a, b) => a.home.localeCompare(b.home));
  const registry = readJson(join(repoRoot, 'docs', 'procedures', 'registry.json')).procedures;
  const auditById = new Map(auditProcedures(repoRoot).map((item) => [item.id, item]));
  const procedures = registry.map((procedure) => {
    const manifest = readProcedureManifest(repoRoot, procedure);
    const digest = readReadmeDigest(
      procedure.homePath ? join(repoRoot, procedure.homePath, 'README.md') : null,
    );
    return {
      ...procedure,
      slug: procedureSlug(procedure.id),
      title: digest.title ?? procedure.id,
      summary: digest.summary,
      manifest,
      migrationState: migrationState(procedure),
      buildState: auditById.get(procedure.id)?.state ?? 'unknown',
      // Причины невалидности нужны витрине, чтобы отличить названный долг от поломки
      // (см. buildStateNote). Состояние без причины читается снаружи как авария.
      problems: auditById.get(procedure.id)?.problems ?? [],
      portfolio: auditById.get(procedure.id)?.portfolio ?? { status: 'missing', count: 0, items: [] },
    };
  });
  return { workshops, procedures };
}

function frontmatter(title, description) {
  return [
    '---',
    `title: ${JSON.stringify(mdx(title))}`,
    `description: ${JSON.stringify(mdx(description))}`,
    '---',
    '',
    GENERATED_NOTICE,
    '',
  ];
}

function workshopCommands(workshop) {
  const commands = Object.entries(workshop.commands ?? {}).filter(([, value]) => value);
  if (commands.length === 0) return ['Команды пока не объявлены.'];
  return commands.map(([name, value]) => value.startsWith('planned:')
    ? `- **${mdx(name)}:** запланировано, но ещё не исполнимо — \`${mdx(value.slice(8).trim())}\``
    : `- **${mdx(name)}:** \`${mdx(value)}\``);
}

function workshopExamples(workshop) {
  const examples = Object.entries(workshop.usage ?? {});
  if (examples.length === 0) {
    return ['<Warning>', `Проверенного примера пока нет. Его накопит \`${EXAMPLE_TASK}\`.`, '</Warning>'];
  }
  const lines = [];
  for (const [name, example] of examples) {
    lines.push(`### ${mdx(name)}`, '', mdx(example.what), '', '```text', String(example.sample ?? '').trim(), '```');
    if (example.measuredAt) lines.push('', `Проверено: ${mdx(example.measuredAt)}.`);
    if (example.source) lines.push('', `[Источник примера](${sourceUrl(example.source)})`);
    lines.push('');
  }
  return lines;
}

export function renderWorkshopPage(workshop) {
  const lines = frontmatter(workshop.title ?? workshop.name, workshop.summary ?? `Мастерская ${workshop.home}`);
  lines.push(
    workshop.summary ? mdx(workshop.summary) : 'Краткое назначение пока не опубликовано.',
    '',
    '## Что она обрабатывает',
    '',
    `- **Дом:** [\`${mdx(workshop.home)}\`](${sourceUrl(`${workshop.home}/README.md`)})`,
    `- **Предмет:** \`${mdx(workshop.worksOn)}\``,
    `- **Плоскость:** ${mdx(workshop.plane)}`,
    `- **Роль:** ${mdx(workshop.role ?? 'не объявлена')}`,
    `- **Состояние:** ${workshop.valid ? 'манифест читается' : 'манифест требует ремонта'}`,
    '',
    '## Как войти',
    '',
    ...workshopCommands(workshop),
    '',
    '## Примеры',
    '',
    ...workshopExamples(workshop),
    '',
    '## Портфолио',
    '',
    '<Note>',
    `Отдельное портфолио мастерской не объявлено. Примеры выше считаются только по полю \`usage\`; пробелы копит \`${EXAMPLE_TASK}\`.`,
    '</Note>',
  );
  return `${lines.join('\n').trim()}\n`;
}

function itemLines(items, empty) {
  return items?.length ? items.map((item) => `- \`${mdx(item.id)}\` — ${mdx(item.holder ?? item.criticality)}`) : [empty];
}

function gateLines(manifest) {
  const gates = manifest?.gates?.items ?? [];
  return gates.length > 0
    ? gates.map((gate) => `- **${mdx(gate.id)}:** ждёт ${mdx(gate.waitsFor)}; продолжение — ${mdx(gate.resume)}`)
    : ['Явные гейты в манифесте не опубликованы.'];
}

function portfolioLines(procedure) {
  const items = procedure.portfolio?.items ?? [];
  if (items.length === 0) {
    return ['<Warning>', `Портфолио отсутствует. Пробел копит \`${EXAMPLE_TASK}\`.`, '</Warning>'];
  }
  const lines = items.map((item) => item.path
    ? `- [${mdx(item.id ?? item.kind)}](${sourceUrl(item.path)}) — ${mdx(item.kind)}`
    : `- ${mdx(item.id ?? item.kind)} — ${mdx(item.kind)}`);
  const lived = items.some((item) => ['run', 'precedent', 'protocol', 'journal'].includes(item.kind));
  if (!lived) lines.push('', '<Warning>', `Есть носители, но нет прожитого примера. Пробел копит \`${EXAMPLE_TASK}\`.`, '</Warning>');
  return lines;
}

export function renderProcedurePage(procedure) {
  const manifest = procedure.manifest;
  const lines = frontmatter(procedure.title, procedure.summary ?? `Процедура ${procedure.id}`);

  lines.push(
    procedure.summary ? mdx(procedure.summary) : 'Краткое назначение пока не опубликовано.',
    '',
    '## Паспорт',
    '',
    `- **ID:** \`${mdx(procedure.id)}\``,
    `- **Род:** ${mdx(procedure.procedureKind)}`,
    `- **Держатель:** ${mdx(procedure.holder)}`,
    `- **Состояние:** \`${mdx(procedure.buildState)}\`${buildStateNote(procedure)}`,
    `- **Миграция:** \`${mdx(procedure.migrationState)}\``,
  );
  if (procedure.homePath) lines.push(`- **Канон:** [\`${mdx(procedure.homePath)}\`](${sourceUrl(`${procedure.homePath}/README.md`)})`);
  lines.push(
    '',
    '## Когда входить',
    '',
    manifest?.trigger?.note ? mdx(manifest.trigger.note) : 'Триггер пока не опубликован.',
  );
  if (manifest?.trigger?.command) lines.push('', `Команда или фраза входа: \`${mdx(manifest.trigger.command)}\``);
  lines.push(
    '',
    '## Этапы',
    '',
    ...itemLines(manifest?.frames, 'Кадры пока не опубликованы.'),
    '',
    '## Гейты',
    '',
    ...gateLines(manifest),
    '',
    '## Выходы и примеры',
    '',
    ...portfolioLines(procedure),
  );
  return `${lines.join('\n').trim()}\n`;
}

export function isProcedurePublished(procedure) {
  const manifest = procedure.manifest;
  const hasOperationalEvidence = Boolean(
    manifest?.trigger?.note
    || manifest?.trigger?.command
    || manifest?.frames?.length
    || manifest?.gates?.items?.length
    || procedure.portfolio?.items?.length,
  );
  return procedure.buildState !== 'declared-not-built'
    && Boolean(procedure.summary)
    && hasOperationalEvidence;
}

function renderIndex(kind, items) {
  const noun = kind === 'workshops' ? 'мастерских' : 'процедур';
  const lines = frontmatter(kind === 'workshops' ? 'Мастерские' : 'Процедуры', `Живой индекс ${noun} Membrana.`);
  lines.push(
    `Здесь ${items.length} ${noun}. Каждая карточка ведёт на отдельную страницу, собранную из живого канона.`,
    '',
    '<CardGroup cols={2}>',
  );
  for (const item of items) {
    lines.push(`<Card title="${mdx(item.title ?? item.name)}" href="/${kind}/${item.slug}">`, mdx(item.summary ?? item.home ?? item.id), '</Card>');
  }
  lines.push('</CardGroup>');
  return `${lines.join('\n').trim()}\n`;
}

function renderProcedureIndex(procedures) {
  const published = procedures.filter(isProcedurePublished);
  const declared = procedures.filter((item) => !isProcedurePublished(item));
  const lines = frontmatter('Процедуры', 'Живой индекс процедур Membrana.');
  lines.push(
    `Здесь ${published.length} содержательно описанных процедур. Каждая карточка ведёт на отдельную страницу, собранную из живого канона.`,
    '',
    '<CardGroup cols={2}>',
  );
  for (const item of published) {
    lines.push(
      `<Card title="${mdx(item.title)}" href="/procedures/${item.slug}">`,
      mdx(item.summary),
      '</Card>',
    );
  }
  lines.push('</CardGroup>');
  if (declared.length > 0) {
    lines.push(
      '',
      '## Ещё не готовы к основной навигации',
      '',
      `У этих ${declared.length} записей пока нет достаточного набора: назначения и хотя бы одного входа, этапа, гейта или прожитого выхода. Отдельные страницы сохранены как честные карточки состояния, а пробел копит \`${EXAMPLE_TASK}\`.`,
      '',
      '| ID | Держатель | Состояние |',
      '|---|---|---|',
      ...declared.map((item) => `| ${mdx(item.id)} | ${mdx(item.holder)} | ${mdx(item.buildState)} |`),
    );
  }
  return `${lines.join('\n').trim()}\n`;
}

function renderDocsJson(repoRoot, model) {
  const path = join(repoRoot, 'apps', 'docs-harness', 'docs.json');
  const config = readJson(path);
  const generatedNames = new Set(['Мастерские', 'Процедуры']);
  const groups = config.navigation.groups.filter((group) => !generatedNames.has(group.group));
  groups.unshift(
    { group: 'Мастерские', pages: ['workshops/index', ...model.workshops.map((item) => `workshops/${item.slug}`)] },
    {
      group: 'Процедуры',
      pages: ['procedures/index', ...model.procedures.filter(isProcedurePublished).map((item) => `procedures/${item.slug}`)],
    },
  );
  return `${JSON.stringify({ ...config, navigation: { ...config.navigation, groups } }, null, 2)}\n`;
}

export function renderWorkflowDocs(repoRoot) {
  const model = loadWorkflowDocsModel(repoRoot);
  const outputs = {
    'apps/docs-harness/workshops/index.mdx': renderIndex('workshops', model.workshops),
    'apps/docs-harness/procedures/index.mdx': renderProcedureIndex(model.procedures),
    'apps/docs-harness/docs.json': renderDocsJson(repoRoot, model),
  };
  for (const workshop of model.workshops) outputs[`apps/docs-harness/workshops/${workshop.slug}.mdx`] = renderWorkshopPage(workshop);
  for (const procedure of model.procedures) outputs[`apps/docs-harness/procedures/${procedure.slug}.mdx`] = renderProcedurePage(procedure);
  return outputs;
}

function generatedFiles(repoRoot) {
  const files = [];
  for (const dir of ['workshops', 'procedures']) {
    const root = join(repoRoot, 'apps', 'docs-harness', dir);
    if (!existsSync(root)) continue;
    for (const name of readdirSync(root)) {
      const path = join(root, name);
      if (name.endsWith('.mdx') && readFileSync(path, 'utf8').includes(GENERATED_NOTICE)) files.push(path);
    }
  }
  return files;
}

export function writeWorkflowDocs(repoRoot) {
  const outputs = renderWorkflowDocs(repoRoot);
  const expected = new Set(Object.keys(outputs).map((path) => join(repoRoot, path)));
  for (const path of generatedFiles(repoRoot)) if (!expected.has(path)) unlinkSync(path);
  for (const [relativePath, body] of Object.entries(outputs)) {
    const path = join(repoRoot, relativePath);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body, 'utf8');
  }
  return Object.keys(outputs);
}

export function checkWorkflowDocs(repoRoot) {
  const outputs = renderWorkflowDocs(repoRoot);
  const expected = new Set(Object.keys(outputs).map((path) => join(repoRoot, path)));
  const drift = Object.entries(outputs)
    .filter(([relativePath, body]) => !existsSync(join(repoRoot, relativePath)) || readFileSync(join(repoRoot, relativePath), 'utf8') !== body)
    .map(([relativePath]) => relativePath);
  for (const path of generatedFiles(repoRoot)) if (!expected.has(path)) drift.push(path.slice(repoRoot.length + 1));
  return drift.sort();
}
