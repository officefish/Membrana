/**
 * procedure-personas — словарь персон процедур, разведённый на две роли (ADR-0025 Р2).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Прежний `PROCEDURE_PERSONAS` жил внутри `validate-procedure.mjs`
 * (912 строк), а импортировали его уже трое снаружи — `one-shot-run.mjs` и два зуба. Словарь
 * перерос файл валидатора: он не деталь проверки, он общий ростер. Вынос чинит уже
 * случившееся расхождение, а не готовит будущее.
 *
 * ПОЧЕМУ ДВА СПИСКА, А НЕ ОДИН. ADR-0015 ввёл `holder` формой и не определил содержанием;
 * валидатор проверял единственное — членство в общем списке, где модератор стоял наравне с
 * разработчиками. Ангелина ведёт моменты с владельцем, но кода не пишет (кодекс #922), и
 * назначение её держателем валидатор не просто допускал — благословлял. Отсюда 20 фреймов
 * из 87 (23%), у чьих дефектов нет исполнителя по построению.
 *
 * ПОЧЕМУ МОДЕРАТОРЫ ВЫЧИСЛЯЮТСЯ, А НЕ ПЕРЕЧИСЛЕНЫ (разбор Дынина 08.08). Перечисление двух
 * списков разъедется при добавлении седьмой персоны, и никто не заметит — ровно так
 * `PERSONA_ROLE_LABELS` шесть дней не знал, что Тарасов стал тимлидом (#1644). Целое
 * (отношение ⊇) обязано управлять частями, а не собираться из их совпадения. Скрытие
 * состава лечится зубом, а не дублированием строк.
 */

/**
 * Кто касается кода — и потому может быть держателем фрейма.
 *
 * Состав — из ADR-0025 Р2 дословно. Ангелины здесь нет намеренно: модератор в `holder` —
 * ошибка валидатора, а не предупреждение (молчаливое допущение и создало нынешние 20).
 */
export const HOLDER_PERSONAS = Object.freeze([
  'vesnin',
  'ozhegov',
  'dynin',
  'kuryokhin',
  'rodchenko',
  'tarasov',
]);

/**
 * Кто может вести момент. Разработчик — тоже может: роли ортогональны и совпадают законно
 * (у `magistral-gate` модератор Ангелина, а держатель — тот, кто чинит предикаты гейта).
 *
 * Вычисляется объединением: см. шапку про разъезжающиеся списки.
 */
export const MODERATOR_PERSONAS = Object.freeze([...HOLDER_PERSONAS, 'angelina']);

/**
 * Опознать проблему как НАЗВАННЫЙ долг ADR-0025 (модератор в держателях).
 *
 * Единственное место, где живёт это опознание. До 08.08 та же регулярка стояла двумя
 * копиями — в ревизии корпуса и в зубах, — и ревью справедливо дало P2: «при смене текста
 * `holderProblem` фильтр молча сломается» (#1792). Копия рядом с производителем причины
 * ломается вместе с ним и потому чинится вместе с ним.
 *
 * Долг ≠ дефект: он назван, посчитан и ждёт отдельной задачи #1787. Пока он не закрыт,
 * потребители имеют право отличать его от постороннего дефекта — но НЕ прятать.
 *
 * @param {unknown} problem строка проблемы валидатора
 */
export function isAdr0025Debt(problem) {
  return typeof problem === 'string' && problem.includes(MODERATOR_IN_HOLDER_MARK);
}

/** Опорная подстрока причины. Меняется только вместе с текстом в `holderProblem`. */
export const MODERATOR_IN_HOLDER_MARK = 'модератор: ведёт момент';

/** @param {unknown} p */
export function isHolderPersona(p) {
  return typeof p === 'string' && HOLDER_PERSONAS.includes(p);
}

/** @param {unknown} p */
export function isModeratorPersona(p) {
  return typeof p === 'string' && MODERATOR_PERSONAS.includes(p);
}

/**
 * Причина отказа для `holder` — названная, а не «∉ список».
 *
 * Модератор в держателях — отдельный род ошибки: у такого фрейма исполнителя нет по
 * построению, и сказать это надо словами, иначе следующий читатель решит, что достаточно
 * дописать имя в список.
 *
 * @param {unknown} p
 * @returns {string|null} причина или null, если держатель годен
 */
export function holderProblem(p) {
  if (isHolderPersona(p)) return null;
  if (typeof p === 'string' && p === 'angelina') {
    // Метка вшита В САМУ причину, а не продублирована рядом: опознание долга и его
    // формулировка обязаны меняться вместе. Иначе правка текста молча ломает фильтр —
    // ровно то, что назвало ревью PR #1793 и что записано предметом в #1792.
    return `holder «${p}» — ${MODERATOR_IN_HOLDER_MARK}, но кода не пишет (кодекс #922), у фрейма не будет исполнителя. Модератора называть полем moderator`;
  }
  return `holder ∉ HOLDER_PERSONAS (${HOLDER_PERSONAS.join('/')})`;
}
