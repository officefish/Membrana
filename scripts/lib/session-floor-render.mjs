/**
 * Рендер пола сессии (§6 контракта `workshop-wires`).
 *
 * ЕДИНСТВЕННЫЙ ВХОД — ПРОЕКЦИЯ. Функции этого модуля не читают ни ФС, ни git, ни реестр:
 * всё приходит готовым из [`session-floor.mjs`](./session-floor.mjs). Так запрет §6 «ручная
 * запись в текст выдачи» держится конструкцией — дописать строку неоткуда.
 *
 * ПОРОГ СЖАТИЯ ПОСЧИТАН, А НЕ НАЗНАЧЕН. Комната M6 поставила «не более сорока строк» на
 * глаз; аудитор Фаррелл посчитал против её же чисел и получил 30–38 строк уже на сегодняшнем
 * составе — то есть сжатая форма рискует включиться на следующей же мастерской, ничего не
 * сломав, но обесценив полную выдачу. Оговорка требовала проверить порог при реализации.
 *
 * АРИФМЕТИКА — ЗАМЕР, а не оценка (31.07, 13 мастерских, 12 вызовов):
 *
 * ```text
 * штампы свежести                4
 * заголовок «мастерские (13):»   1
 * мастерские                    13   по строке на дом — единственное, что растёт
 * вызовы                         1   ОДНОЙ строкой через разделитель, не по строке на вызов
 * строка политики                1
 * ссылка на документацию         1
 * отчёт уровня 1 (ok)            1
 * ───────────────────────────────
 * итого                         22   из 40
 * ```
 *
 * ВЫВОД ПРОТИВОРЕЧИТ ОБЕИМ ПРЕЖНИМ ОЦЕНКАМ. Комната ждала, что сорок строк — живой потолок;
 * аудитор считал 30–38 уже сегодня и ждал, что сжатие включится вот-вот. Факт — 22, и
 * растёт только список домов: бюджет в сорок строк достигается примерно на **31-й**
 * мастерской. Но §6 включает сжатие ещё и «более пятнадцати мастерских», то есть на
 * **16-й** — вдвое раньше.
 *
 * Значит **порог в сорок строк практически мёртв**: счётчик мастерских сработает первым и
 * всегда. Он оставлен как второй заслон на случай, если состав выдачи разрастётся не домами
 * (длинные штампы, многострочный отчёт деградации), и {@link FLOOR_LINE_BUDGET} экспортирован
 * — чтобы следующий спор шёл о числе, а не о памяти. Ошибка аудита была в допущении, что
 * вызовы печатаются по строке на каждый; она честно называется здесь, а не заминается.
 */

/** Потолок строк полной выдачи (§6). Подтверждён арифметикой выше, не назначен заново. */
export const FLOOR_LINE_BUDGET = 40;

/** Форма выдачи. Список ЗАКРЫТ. */
export const FLOOR_SHAPES = Object.freeze({ FULL: 'full', COMPACT: 'compact', WARM: 'warm' });

/**
 * Строки полной выдачи холодной сессии.
 *
 * Порядок из §6 и не переставляется: полоса статуса и штампы → мастерские → вызовы →
 * политика → ссылка → отчёт. Отчёт последним потому, что он про качество предыдущего;
 * поставить его первым (кроме случая DEGRADED, где §6 требует именно этого) значило бы
 * заставить читателя оценивать полноту раньше, чем он увидит содержимое.
 */
export function renderFloor(floor, health, opts = {}) {
  const shape = opts.warm === true
    ? FLOOR_SHAPES.WARM
    : floor.compact ? FLOOR_SHAPES.COMPACT : FLOOR_SHAPES.FULL;

  const lines = [];
  const degraded = health?.health === 'degraded';

  // §6: при деградации полоса идёт первой строкой — до всего остального.
  const healthLines = opts.renderHealth ? opts.renderHealth(health) : [];
  if (degraded) lines.push(...healthLines);

  if (Array.isArray(floor.stamps?.lines)) lines.push(...floor.stamps.lines);
  else if (typeof floor.stamps?.text === 'string') lines.push(floor.stamps.text);

  if (shape === FLOOR_SHAPES.WARM) {
    // Тёплая сессия: только штампы и отчёт, без повторной печати каталога (§6).
    if (!degraded) lines.push(...healthLines);
    return lines;
  }

  if (shape === FLOOR_SHAPES.COMPACT) {
    // Сжатая форма: счётчик вместо перечня. Счётчик берётся из проекции, а не из длины
    // напечатанного списка — иначе сжатие соврало бы о числе домов.
    lines.push(`мастерских ${floor.workshopCount} · перечень свёрнут (> ${opts.manyWorkshops ?? 15}) — \`yarn tooling:overview\``);
  } else {
    lines.push(`мастерские (${floor.workshopCount}):`);
    for (const w of floor.workshops) {
      // ВСЕ команды мастерской в строке, а не одна входная. Холодная сессия 31.07 дважды
      // ходила грепать package.json за именами не-входных глаголов: пол давал дверь в дом и
      // не давал ключей от комнат. Строка одна на мастерскую — число строк не растёт.
      const verbs = Array.isArray(w.verbs) && w.verbs.length > 0 ? w.verbs : [w.entryVerb ?? '—'];
      const mark = w.valid === false ? ' ⚠' : '';
      lines.push(`  ${w.home}${mark} · ${verbs.join(' · ')}${w.description ? ` · ${w.description}` : ''}`);
    }
  }

  const { calls, dropped } = floor.callable;
  if (calls.length > 0) {
    lines.push(`вызовы: ${calls.join(' · ')}${dropped > 0 ? ` … и ещё ${dropped}` : ''}`);
  }
  lines.push(floor.policyLine);
  lines.push(`документация: ${floor.docLink}`);
  if (!degraded) lines.push(...healthLines);

  return lines;
}

/**
 * Проверка бюджета строк.
 *
 * Возвращает предупреждение, а не режет выдачу: §6 говорит «предупреждение при выдаче свыше
 * сорока строк». Молча обрезать значило бы отнять у сессии часть пола и не сказать об этом —
 * ровно то ложное покрытие, которое §7 назвал ценой оптового слоя.
 */
export function checkBudget(lines, budget = FLOOR_LINE_BUDGET) {
  return lines.length <= budget
    ? { ok: true, lines: lines.length, budget, warning: null }
    : {
      ok: false,
      lines: lines.length,
      budget,
      warning: `выдача ${lines.length} строк при бюджете ${budget} — пора сжимать форму, а не резать молча`,
    };
}
